import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {attachmentAccept,validateAttachments,uploadAttachments,canAttach,attachmentLimit} from "../public/ticket-attachments.js";
const files=[{name:"Screenshot.png",size:100},{name:"Excel.xlsx",size:100},{name:"Dokument.pdf",size:100}];
assert.equal(validateAttachments(files),files);
assert.match(attachmentAccept,/\.docx/);
assert.throws(()=>validateAttachments([{name:"danger.exe",size:10}]),/nicht erlaubt/);
assert.throws(()=>validateAttachments([{name:"large.pdf",size:attachmentLimit+1}]),/10 MB/);
let calls=[];
const bucket={async upload(path,file,opts){calls.push({path,file,opts});return file.name==="Excel.xlsx"?{error:new Error("storage failure")}:{}}};
const result=await uploadAttachments(bucket,42,"user",files);
assert.equal(result.uploaded.length,2);assert.equal(result.failed.length,1);
assert.match(calls[0].path,/^42\/user\/[a-f0-9-]{36}-Screenshot\.png$/);
assert.equal(calls[1].opts.contentType,"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
assert.equal(calls[0].opts.upsert,false);
assert.equal((await uploadAttachments(bucket,42,"user",files,()=>false)).failed.length,3);
const t={id:42,creator_id:"user",status:"open"};
assert.equal(canAttach(t,"user",false,[]),true);
assert.equal(canAttach(t,"other",false,[]),false);
assert.equal(canAttach(t,"other",false,[{ticket_id:42,user_id:"other",response:"pending"}]),true);
assert.equal(canAttach({...t,status:"closed"},"user",true,[]),false);
assert.equal(canAttach({...t,status:"rejected"},"user",true,[]),false);
const src=readFileSync(new URL("../public/tickets.js",import.meta.url),"utf8");
assert.ok(src.includes("attachmentPicker,createWithAttachments"));
assert.ok(src.includes("await uploadAttachments(bucket,id,u,selected"));
console.log("Ticket attachments: file validation, multi-upload, partial failure, permissions and integration passed");
